// Release signing is read from keystore.properties when present. To publish an
// update to the existing Play listing this MUST point at the original upload
// key -- a different key produces an APK Play will reject.
val keystoreProperties = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

// The backend's base URL, e.g. https://example.org/api/v1.0/ -- nothing about
// the deployment is hardcoded. First match wins:
//   -PapiBaseUrl=...   (or apiBaseUrl=... in ~/.gradle/gradle.properties)
//   API_BASE_URL=...   environment variable
//   apiBaseUrl=...     in local.properties (gitignored, per machine)
val apiBaseUrl: String = run {
    val localProperties = Properties().apply {
        val f = rootProject.file("local.properties")
        if (f.exists()) f.inputStream().use { load(it) }
    }
    val url = (project.findProperty("apiBaseUrl") as String?)
        ?: System.getenv("API_BASE_URL")
        ?: localProperties.getProperty("apiBaseUrl")
        ?: error("Set the backend URL: -PapiBaseUrl=..., API_BASE_URL=... or apiBaseUrl=... in local.properties")
    // Retrofit resolves relative paths against the base URL, which only works
    // when it ends in a slash.
    if (url.endsWith("/")) url else "$url/"
}
val apiUri: URI = URI(apiBaseUrl)
require(apiUri.scheme in setOf("http", "https") && !apiUri.host.isNullOrEmpty()) {
    "apiBaseUrl must be an absolute http(s) URL, got '$apiBaseUrl'"
}

