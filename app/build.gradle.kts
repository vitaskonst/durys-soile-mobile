// network_security_config.xml is generated per variant because it has to name
// the API host, which is only known at build time. Cleartext is permitted for
// that host alone, and only when the URL is http://; debug builds additionally
// allow the emulator's host loopback so they can talk to a local backend.
abstract class NetworkSecurityConfigTask : DefaultTask() {
    @get:Input abstract val cleartextHosts: ListProperty<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val domains = cleartextHosts.get().distinct().joinToString("\n") {
            "        <domain includeSubdomains=\"true\">$it</domain>"
        }
        val domainConfig = if (domains.isEmpty()) "" else """
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |""".trimMargin()
        val xml = outputDir.get().file("xml/network_security_config.xml").asFile
        xml.parentFile.mkdirs()
        xml.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by NetworkSecurityConfigTask in app/build.gradle.kts. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false">
            |        <trust-anchors>
            |            <certificates src="system" />
            |        </trust-anchors>
            |    </base-config>
            |$domainConfig</network-security-config>
            |""".trimMargin()
        )
    }
}

androidComponents {
    onVariants { variant ->
        val task = tasks.register<NetworkSecurityConfigTask>(
            "generate${variant.name.replaceFirstChar { it.uppercase() }}NetworkSecurityConfig"
        ) {
            val apiHost = if (apiUri.scheme == "http") listOf(apiUri.host) else emptyList()
            val loopback = if (variant.buildType == "debug") listOf("10.0.2.2", "localhost") else emptyList()
            cleartextHosts.set(apiHost + loopback)
        }
        variant.sources.res?.addGeneratedSourceDirectory(task, NetworkSecurityConfigTask::outputDir)
    }
}

